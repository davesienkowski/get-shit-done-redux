#!/usr/bin/env node
'use strict';

/**
 * Generates docs/reference/probe-manifest.md from the probe registry
 * (`gsd-core/bin/lib/probe-registry.cjs`, built from `src/probe-registry.cts`).
 *
 * The manifest is a DERIVED artifact: it is rendered from `PROBE_REGISTRY`, so the
 * human-facing "what does each probe classify?" reference can never silently drift
 * from the live taxonomies the way the hand-written prose reference docs can. CI
 * re-runs this with `--check` (in `lint:generated-sync`) and fails on any diff.
 *
 * GOODHART GUARD: every taxonomy row is worded as a *question the probe can raise*,
 * never "coverage" / "considerations caught". The classifier is a signal; the
 * human/LLM confirm step is what makes coverage sound (ADR-20 D3).
 *
 * Usage:
 *   node scripts/gen-probe-manifest.cjs            # print to stdout
 *   node scripts/gen-probe-manifest.cjs --write    # (re)write the manifest file
 *   node scripts/gen-probe-manifest.cjs --check    # exit 1 if the committed file is stale
 */

const fs = require('node:fs');
const path = require('node:path');

const { ExitError, runMain } = require('./lib/cli-exit.cjs');

const ROOT = path.resolve(__dirname, '..');
const REGISTRY_PATH = path.join(ROOT, 'gsd-core', 'bin', 'lib', 'probe-registry.cjs');
const MANIFEST_PATH = path.join(ROOT, 'docs', 'reference', 'probe-manifest.md');

/** Escape a taxonomy string for a markdown table cell. */
function cell(text) {
  return String(text).replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
}

/**
 * Render the manifest markdown from a probe registry (an array of ProbeDescriptor).
 * Exported so a unit test can assert the render without spawning the CLI.
 */
function renderManifest(registry) {
  const out = [
    '<!-- Generated by scripts/gen-probe-manifest.cjs from src/probe-registry.cts — do not edit by hand. -->',
    '',
    '# Probe manifest',
    '',
    'The spec-phase **probe family** — one row per axis, rendered from the live `PROBE_REGISTRY` (ADR-20).',
    'Each taxonomy entry is a **question this probe can raise**, not a guarantee of what it catches: the',
    'classifier is a signal, and the human/LLM confirm step is what makes coverage sound.',
    '',
    '| Axis | Title | Propose | Verification tiers | Relevance vocabulary |',
    '|------|-------|---------|--------------------|----------------------|',
  ];
  for (const d of registry) {
    const relevance = d.relevance
      ? `${cell(d.relevance.name)}: ${d.relevance.vocabulary.map(cell).join(', ')}`
      : '— (open-vocabulary)';
    out.push(
      `| \`${cell(d.axis)}\` | ${cell(d.title)} | ${cell(d.proposeKind)} | ${d.verificationTiers.map((t) => `\`${cell(t)}\``).join(' \\| ')} | ${relevance} |`,
    );
  }
  out.push('');

  for (const d of registry) {
    out.push(`## \`${d.axis}\` — ${cell(d.title)}`, '');
    out.push(`- **Invoke:** \`${cell(d.invoke)}\``);
    out.push(`- **Propose:** ${cell(d.proposeKind)}${d.proposeKind === 'llm-recall' ? ' (LLM adversarial recall — no closed taxonomy)' : ''}`);
    out.push(`- **Verification tiers:** ${d.verificationTiers.map((t) => `\`${cell(t)}\``).join(', ')}`, '');
    if (d.taxonomy === null) {
      out.push('_Open-vocabulary probe — no closed category taxonomy; recall enumerates the constraints at runtime._', '');
      continue;
    }
    out.push('| Category | Applies to | Question this probe can raise |', '|----------|------------|-------------------------------|');
    for (const t of d.taxonomy) {
      out.push(`| \`${cell(t.id)}\` | ${t.applicableTo.map(cell).join(', ')} | ${cell(t.question)} |`);
    }
    out.push('');
  }
  return out.join('\n') + '\n';
}

/** Normalize CRLF so `--check` compares content, not line endings. */
function normalize(s) {
  return s.replace(/\r\n/g, '\n');
}

function loadRegistry() {
  if (!fs.existsSync(REGISTRY_PATH)) {
    throw new ExitError(1, `probe registry not built at ${REGISTRY_PATH}. Run: npm run build:lib\n`);
  }
  // Reload fresh each run (the build emits it); require cache is irrelevant for a one-shot CLI.
  const { PROBE_REGISTRY } = require(REGISTRY_PATH);
  return PROBE_REGISTRY;
}

function main() {
  const [, , flag] = process.argv;
  const manifest = renderManifest(loadRegistry());

  if (flag === '--check') {
    if (!fs.existsSync(MANIFEST_PATH)) {
      process.stderr.write('docs/reference/probe-manifest.md is missing. Run:\n  node scripts/gen-probe-manifest.cjs --write\n');
      throw new ExitError(1);
    }
    if (normalize(fs.readFileSync(MANIFEST_PATH, 'utf8')) !== normalize(manifest)) {
      process.stderr.write('docs/reference/probe-manifest.md is stale. Run:\n  node scripts/gen-probe-manifest.cjs --write\n');
      throw new ExitError(1);
    }
    process.stdout.write('docs/reference/probe-manifest.md is up to date.\n');
  } else if (flag === '--write') {
    fs.writeFileSync(MANIFEST_PATH, manifest);
    process.stdout.write(`Wrote ${MANIFEST_PATH}.\n`);
  } else {
    process.stdout.write(manifest);
  }
}

module.exports = { renderManifest };

if (require.main === module) runMain(main);
